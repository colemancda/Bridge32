#!/usr/bin/env python3
"""Assembles PowerPC test code into a C++ header, so tests need no assembler.

Xcode's clang has no PowerPC target, but any LLVM build that has one (the
Swift toolchain's, Homebrew's llvm) assembles it, as ELF: only the machine
words matter here, so the object's .text is read straight out of the file.

    ppc-asm.py tests/ppc/cpu-test.s tests/ppc/cpu-test-code.h

The header holds the words (each with its disassembly, when llvm-objdump is
around) and a constant for every label that doesn't start with .L: its offset
in bytes from the start of the code. Run it again after editing the .s file
and commit both; the generated header is what the tests build against.

Set CLANG to use a particular clang, which must list ppc32 in -print-targets.
"""
import os
import re
import shutil
import struct
import subprocess
import sys
import tempfile


def find_clang():
    candidates = [os.environ.get("CLANG")] if os.environ.get("CLANG") else []
    candidates += ["clang", "xcrun clang"]
    for command in candidates:
        argv = command.split()
        try:
            targets = subprocess.run(argv + ["-print-targets"], capture_output=True, text=True).stdout
        except FileNotFoundError:
            continue
        if re.search(r"^\s*ppc32\b", targets, re.M):
            return argv
    sys.exit("no clang with a PowerPC target found; set CLANG to one")


def elf_sections(data):
    if data[:4] != b"\x7fELF" or data[4] != 1 or data[5] != 2:
        sys.exit("not a 32-bit big-endian ELF object")
    shoff, = struct.unpack(">I", data[0x20:0x24])
    shentsize, shnum, shstrndx = struct.unpack(">3H", data[0x2E:0x34])
    raw = []
    for i in range(shnum):
        raw.append(struct.unpack(">10I", data[shoff + i * shentsize: shoff + i * shentsize + 40]))
    names = raw[shstrndx]
    strtab = data[names[4]: names[4] + names[5]]
    sections = {}
    for index, (name, kind, flags, addr, offset, size, link, info, align, entsize) in enumerate(raw):
        label = strtab[name:strtab.index(b"\0", name)].decode()
        sections[label] = (index, offset, size, link)
    return sections


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    source, header = sys.argv[1:]
    clang = find_clang()
    with tempfile.TemporaryDirectory() as work:
        obj = os.path.join(work, "code.o")
        subprocess.run(clang + ["-target", "powerpc-unknown-linux-gnu", "-mcpu=7400", "-maltivec", "-c", "-o", obj, source],
                       check=True)
        data = open(obj, "rb").read()
        sections = elf_sections(data)
        text_index, text_offset, text_size, _ = sections[".text"]
        code = data[text_offset: text_offset + text_size]
        _, sym_offset, sym_size, strtab_index = sections[".symtab"]
        strtab_section = [s for s in sections.values() if s[0] == strtab_index][0]
        strings = data[strtab_section[1]: strtab_section[1] + strtab_section[2]]
        symbols = []
        for i in range(sym_size // 16):
            name, value, size, info, other, shndx = struct.unpack(">3IBBH", data[sym_offset + i * 16: sym_offset + i * 16 + 16])
            label = strings[name:strings.index(b"\0", name)].decode()
            if shndx == text_index and label and not label.startswith(".L"):
                symbols.append((value, label))
        notes = {}
        objdump = shutil.which("llvm-objdump")
        if objdump:
            listing = subprocess.run([objdump, "-d", "--no-show-raw-insn", obj], capture_output=True, text=True).stdout
            for line in listing.splitlines():
                m = re.match(r"\s*([0-9a-f]+):\s+(.*\S)", line)
                if m:
                    notes[int(m.group(1), 16)] = re.sub(r"\s+", " ", m.group(2))
    labels_at = {}
    for value, label in sorted(symbols):
        labels_at.setdefault(value, []).append(label)
    out = ["// Generated by tools/ppc-asm.py from " + os.path.basename(source) + "; do not edit.",
           "#pragma once", "", "#include <cstdint>", "", "namespace ppccode {", "",
           "// Byte offsets of the labels, from the start of kWords."]
    for value, label in sorted(symbols):
        name = "k" + "".join(part.capitalize() for part in re.split(r"[_]+", label))
        out.append(f"constexpr uint32_t {name} = 0x{value:x};")
    out += ["", "constexpr uint32_t kWords[] = {"]
    for i in range(len(code) // 4):
        word, = struct.unpack(">I", code[i * 4: i * 4 + 4])
        for label in labels_at.get(i * 4, []):
            out.append(f"    // {label}:")
        note = notes.get(i * 4)
        out.append(f"    0x{word:08x},{('  // ' + note) if note else ''}")
    out += ["};", "", "}  // namespace ppccode", ""]
    open(header, "w").write("\n".join(out))


main()
