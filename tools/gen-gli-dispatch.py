#!/usr/bin/env python3
"""Generates core/gl/gli_dispatch.inc: the OpenGL function behind each slot of a
context's dispatch table, in the table's order.

Programs built with CGLMacro.h or aglMacro.h don't call glClear(...): they call
through the context record, (*ctx->disp.clear)(ctx->rend, ...). The table's
layout is gliDispatch.h's struct, and CGLMacro.h says which function each field
is. Both come from the macOS SDK's OpenGL.framework.

    tools/gen-gli-dispatch.py > core/gl/gli_dispatch.inc
"""
import re
import subprocess
import sys

sdk = subprocess.run(["/usr/bin/xcrun", "--sdk", "macosx", "--show-sdk-path"], capture_output=True, text=True).stdout.strip()
if len(sys.argv) > 1:
    sdk = sys.argv[1]
headers = sdk + "/System/Library/Frameworks/OpenGL.framework/Headers/"
dispatch = open(headers + "gliDispatch.h", encoding="latin-1").read()
macros = open(headers + "CGLMacro.h", encoding="latin-1").read()

# Every field takes the context first: "void (*accum)(GLIContext ctx, ...)".
fields = re.findall(r"\(\*(\w+)\)\s*\(\s*GLIContext\b", dispatch)

# "#define glAccum(op, value) \ (*(CGL_MACRO_CONTEXT)->disp.accum)(CGL_MACRO_CONTEXT_RENDERER, op, value)".
# The first name defined for a field is the one kept (later ones are aliases).
function = {}
for name, field in re.findall(r"#define\s+(gl\w+)\s*\([^)]*\)\s*(?:\\\s*)?\(\*\(CGL_MACRO_CONTEXT\)->disp\.(\w+)\)", macros):
    function.setdefault(field, name)

print("// Generated by tools/gen-gli-dispatch.py from the macOS SDK's gliDispatch.h and CGLMacro.h:")
print("// the OpenGL function behind each slot of a context's dispatch table, in order.")
for field in fields:
    if field in function:
        print(f'    "{function[field]}",')
    else:
        print(f"    nullptr,  // {field}")
