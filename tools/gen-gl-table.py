#!/usr/bin/env python3
"""Generates core/gl/opengl_table.inc, the table of desktop OpenGL functions
for core/gl/opengl.mm, from the macOS SDK's gl.h and glext.h.

    tools/gen-gl-table.py > core/gl/opengl_table.inc

Functions a 32-bit guest can't call through the table (64-bit integer or
sync-object arguments) are left out; glMapBuffer and friends, which return
host pointers, are left to hand-written thunks.
"""
import re
import subprocess

SDK = subprocess.check_output(["xcrun", "--sdk", "macosx", "--show-sdk-path"], text=True).strip()
HEADERS = [f"{SDK}/System/Library/Frameworks/OpenGL.framework/Headers/{h}" for h in ("gl.h", "glext.h")]

# Vertex array pointers and index pointers: offsets when a buffer is bound.
ARRAY = {"glVertexPointer", "glNormalPointer", "glColorPointer", "glIndexPointer", "glTexCoordPointer",
         "glEdgeFlagPointer", "glFogCoordPointer", "glFogCoordPointerEXT", "glSecondaryColorPointer",
         "glSecondaryColorPointerEXT", "glVertexAttribPointer", "glVertexAttribPointerARB", "glInterleavedArrays"}
ELEMENT = {"glDrawElements", "glDrawRangeElements", "glDrawRangeElementsEXT", "glDrawElementsBaseVertex",
           "glDrawRangeElementsBaseVertex", "glDrawElementsInstancedBaseVertex", "glDrawElementsInstancedARB",
           "glDrawElementsInstancedEXT", "glDrawElementsInstanced"}
SKIP = {"glMapBuffer", "glMapBufferARB", "glMapBufferRange", "glMapObjectBufferATI", "glCompileShader", "glShaderSource"}

INTEGER = {"GLint": "i", "GLsizei": "i", "GLshort": "i", "GLbyte": "i", "GLclampx": "i", "GLfixed": "i",
           "GLenum": "u", "GLuint": "u", "GLbitfield": "u", "GLboolean": "u", "GLubyte": "u", "GLushort": "u",
           "GLfloat": "f", "GLclampf": "f", "GLdouble": "d", "GLclampd": "d",
           "GLintptr": "z", "GLsizeiptr": "z", "GLintptrARB": "z", "GLsizeiptrARB": "z",
           "GLhandleARB": "h"}
RETURNS = dict(INTEGER, GLboolean="B", void="v")


def code(tokens, is_return, name, index):
    text = " ".join(t for t in tokens if t != "const")
    if "*" in text:
        if is_return:
            return "s" if "GLubyte" in text else None
        if name in ARRAY and index == ARRAY_POSITION.get(name, -1):
            return "a"
        if name in ELEMENT and index == ELEMENT_POSITION.get(name, -1):
            return "e"
        if STRINGS.get(name) == index:
            return "S"
        return "p"
    return (RETURNS if is_return else INTEGER).get(text)


# Arrays of guest C strings, whose length is the argument before them.
STRINGS = {"glShaderSourceARB": 2, "glTransformFeedbackVaryings": 2,
           "glTransformFeedbackVaryingsEXT": 2, "glGetUniformIndices": 2}

# Which argument is the array or index pointer.
ARRAY_POSITION = {n: 3 for n in ARRAY}
ARRAY_POSITION.update({"glNormalPointer": 2, "glIndexPointer": 2, "glEdgeFlagPointer": 1, "glFogCoordPointer": 2,
                       "glFogCoordPointerEXT": 2, "glVertexAttribPointer": 5, "glVertexAttribPointerARB": 5,
                       "glInterleavedArrays": 2})
ELEMENT_POSITION = {n: 3 for n in ELEMENT}
ELEMENT_POSITION.update({"glDrawRangeElements": 5, "glDrawRangeElementsEXT": 5, "glDrawRangeElementsBaseVertex": 5})

proto = re.compile(r"^extern\s+([\w\s*]+?)\s*\b(gl[A-Z]\w+)\s*\(([^)]*)\)", re.M)
seen, skipped, rows = set(), [], []
for header in HEADERS:
    for ret, name, args in proto.findall(open(header).read()):
        if name in seen or name in SKIP:
            continue
        seen.add(name)
        result = code(ret.replace("*", " * ").split(), True, name, -1)
        words = []
        ok = result is not None
        if args.strip() not in ("", "void"):
            for i, arg in enumerate(args.split(",")):
                tokens = arg.replace("*", " * ").split()
                # Drop the parameter's name when it has one.
                if tokens and tokens[-1] != "*" and len(tokens) > 1:
                    tokens = tokens[:-1]
                c = code(tokens, False, name, i)
                if c is None:
                    ok = False
                    break
                words.append(c)
        if ok:
            rows.append((name, f"{result}:{''.join(words)}"))
        else:
            skipped.append(name)

print("// Generated by tools/gen-gl-table.py; do not edit.")
if skipped:
    print("// Left out, not callable through the table: " + " ".join(sorted(skipped)))
for name, sig in sorted(rows):
    print(f'    {{"{name}", "{sig}"}},')
